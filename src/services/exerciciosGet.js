export function somar(num1, num2) {
    return num1 + num2;
}

export function salario(valorHora, horasTrabalhadas) {
    return valorHora * horasTrabalhadas;
}

export function mediaPesos(peso1, peso2, peso3, peso4, peso5) {
    return (peso1 + peso2 + peso3 + peso4 + peso5) / 5;
}

export function conversao(celsius) {
    return (9 * celsius + 160) / 5;
}

export function km(milhas) {
    return milhas * 1.60934;
}